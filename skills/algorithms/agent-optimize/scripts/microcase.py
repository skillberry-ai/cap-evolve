"""microcase — TDD-style micro-tests: reproduce ONE diagnosed failure deterministically,
in seconds, before any real rollout is spent on a candidate.

Adopts Harbor/Terminal-Bench's task shape (``task.yaml`` + fixture/environment + a
``tests/`` dir that asserts pass/fail and writes a reward, no LLM judge required for the
assertion itself), scoped down from "a whole task" to "the one call or turn where a
diagnosed defect lives" — see #434 section 3 and #436.

    $R/microcases/<cluster_id>/
      case.yaml       # {id, cluster_id, source_task_ids, source_rollout, timeout_s,
                       #  expects: guard_fires|call_shape|tool_selected, assert: {...}}
      fixture/          # extracted VERBATIM from the diagnosed rollout — never invented
      reproduce.py      # replays the fixture against the candidate directly: one tool
                        # call / one narrow unit, no full multi-turn episode, no LLM
      assert.py         # deterministic pass/fail against case.yaml's `assert` spec

``reproduce.py``/``assert.py`` are project-specific code (they know the candidate's tool
module) — this script cannot write them for you, only scaffold them from a real diagnosed
rollout so the author fills in the one project-aware step. What IS mechanical: extracting
the tool-call fixture verbatim, and running the case once it exists.

Two subcommands:

    python microcase.py gen  --rollout <path/to/task__tag__tK.json> \\
        --cluster-id netguard_duplicate_payment --expects guard_fires \\
        --description "..." --assert-metric payment_history_len --assert-op "<=" \\
        --assert-value 1 --out $R/microcases/netguard_duplicate_payment

    python microcase.py run  --case $R/microcases/<id> \\
        --candidate $R/work/<tag> --project P [--python PYEXE]

    python microcase.py run-all --cases-dir $R/microcases \\
        --candidate $R/work/<tag> --project P

``run``/``run-all`` never touch the run dir's budget or state — a micro-test is a
pre-rollout filter, not a rollout, and cannot itself accept a candidate (only the full-val
gate can). A ``fail`` here is the new cheap reject basis (``micro_test_fail``, see
``commit.py --reject-basis``): the mechanism the candidate claims to add provably does not
fire, discovered without spending a single evaluation.
"""

