def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--run-dir", required=True)
    ap.add_argument("--seed", type=int, required=True)
    ap.add_argument("--R", type=int, required=True)
    ap.add_argument("--train-ids", required=True)
    ap.add_argument("--val-ids", required=True)
    ap.add_argument("--max-iters", type=int, default=0, help="0 = unbounded (R binds)")
    ap.add_argument("--first-component", default="", help="smoke only: component the round robin visits first")
    a = ap.parse_args()
    run = Path(a.run_dir)
    t_start = time.time()

    def events(rec, stream="events.jsonl"):
        with open(run / stream, "a") as f:
            f.write(json.dumps({"ts": time.time(), **rec}, default=str) + "\n")

    train = [l.strip() for l in open(a.train_ids) if l.strip()]
    val = [l.strip() for l in open(a.val_ids) if l.strip()]
    test = set(map(str, json.load(open(OFFICIAL_SPLIT))["test"]))
    leak = (set(train) | set(val)) & test
    assert not leak, f"refusing: {len(leak)} TEST ids in the search data"
    del test  # never used again

    # Seed bytes must equal the v2 seed recorded in exp895/BUILD_RECORD.json.
    want = json.load(open(EXP / "BUILD_RECORD.json"))["seed_v2"]["files_sha256"]
    seed = seed_candidate(a.first_component or None)
    sdir = materialize(seed, run / "candidates")
    got = tree_sha256(sdir)
    assert got == want, f"seed candidate is not byte-identical to seed_capability_v2: {got} != {want}"

    ro = CommonRollout(run, arm=ARM, search_seed=a.seed, R=a.R)
    all_tasks = {t.id: t for t in ro._adapter.tasks("train")}
    tasks = {}
    for t in train + val:
        x = all_tasks[t].input
        tasks[t] = {"instruction": x["instruction"], "instruction_type": x["instruction_type"],
                    "answer_position": x["answer_position"]}
    del all_tasks
    trainset = [{"id": t} for t in train]
    valset = [{"id": t} for t in val]

    tag = f"exp895-{ARM}-s{a.seed}:optimizer"
    lm = LM("openai/rits/zai-org/glm-5-3", api_base=f"http://127.0.0.1:4115/t/{tag}/v1",
                    api_key="tag-not-a-secret", max_tokens=16000, timeout=3600)
    adapter = GepaFullAdapter(ro, run, tasks, events)
    guards = Guards(adapter, lm, min_eval=K * min(3, len(set(train))))
    rec = Recorder(events)
    stops = [guards]
    if a.max_iters:
        stops.append(MaxCandidateProposalsStopper(a.max_iters))
    cfg = dict(reflection_minibatch_size=3, candidate_selection_strategy="pareto", module_selector="round_robin",
               use_merge=False, cache_evaluation=False, skip_perfect_score=True, perfect_score=1.0,
               max_metric_calls=10**9, seed=a.seed, raise_on_exception=False)
    events({"event": "start", "arm": ARM, "seed": a.seed, "R": a.R, "n_train": len(train), "n_val": len(val),
            "components": list(seed), "gepa_version": "0.1.4", "config": cfg, "max_iters": a.max_iters,
            "first_component": a.first_component, "seed_candidate_dir": sdir.name})
    stop_reason, err = None, None
    try:
        result = gepa.optimize(seed_candidate=seed, trainset=trainset, valset=valset, adapter=adapter,
                               reflection_lm=lm, reflection_prompt_template=reflection_templates(),
                               stop_callbacks=stops, callbacks=[guards, rec], run_dir=str(run / "gepa"), **cfg)
    except BudgetStop as e:  # only possible before the loop (seed val eval did not fit R)
        err = f"BudgetStop before the search loop: {e}"
        result = None
    except Exception as e:  # noqa: BLE001
        err = "".join(traceback.format_exception(e))[-4000:]
        result = None
    if result is None and (run / "gepa" / "gepa_state.bin").exists():
        result = GEPAResult.from_state(GEPAState.load(str(run / "gepa")), run_dir=str(run / "gepa"), seed=a.seed)
    stop_reason = guards.reason or (f"max_iters {a.max_iters}" if a.max_iters and result else None) or err

    summary = {"arm": ARM, "seed": a.seed, "R": a.R, "rollouts_used": ro.spent, "binding_on_R":
               bool(adapter.budget_hit) or ro.remaining() < guards.min_eval, "stop_reason": stop_reason,
               "error": err, "wall_s": round(time.time() - t_start, 1), "adapter_retries": adapter.infra_retries,
               "infra_missing_trials": adapter.infra_missing, "n_evaluate_calls": adapter.n_evals,
               "accepted": rec.accepted, "rejected": rec.rejected,
               "optimizer_lm_tokens_in": lm.total_tokens_in, "optimizer_lm_tokens_out": lm.total_tokens_out}
    if result is not None:
        best = result.best_idx
        champ = materialize(result.candidates[best], run / "candidates")
        shutil.rmtree(run / "champion", ignore_errors=True)
        shutil.copytree(champ, run / "champion", ignore=shutil.ignore_patterns(".complete"))
        summary.update({"champion": champ.name, "champion_idx": best,
                        "champion_val_score": result.val_aggregate_scores[best],
                        "seed_val_score": result.val_aggregate_scores[0],
                        "champion_is_seed": champ.name == sdir.name,
                        "champion_tree_sha256": tree_sha256(run / "champion"),
                        "n_candidates_evaluated": adapter.n_evals,
                        "n_candidates_in_pool": result.num_candidates,
                        "iterations": max(0, (json.load(open(run / "gepa" / "run_log.json"))[-1].get("i", -1) + 1))
                        if (run / "gepa" / "run_log.json").exists() else None,
                        "val_aggregate_scores": result.val_aggregate_scores})
    (run / "run_summary.json").write_text(json.dumps(summary, indent=1, default=str))
    print("GEPA_FULL_SUMMARY", json.dumps(summary, default=str)[:3000], flush=True)
    return 0 if result is not None and err is None else 1


