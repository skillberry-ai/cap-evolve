# Stop conditions and logging (upstream StopperProtocol / GEPACallback interfaces; nothing patched).
# ---------------------------------------------------------------------------------------------------------------
class Guards:
    """Stops GEPA when R can no longer fit the smallest evaluation, when a BudgetStop was raised, when the
    optimizer token cap binds, or after MAX_CONSECUTIVE_ERRORS failed iterations in a row."""

    def __init__(self, adapter: GepaFullAdapter, lm, min_eval: int):
        self.a, self.lm, self.min_eval = adapter, lm, min_eval
        self.consecutive_errors = 0
        self._err_this_iter = False
        self.reason = None

    def __call__(self, state) -> bool:
        if self.a.budget_hit:
            self.reason = "budget_stop: " + self.a.budget_hit
        elif self.a.ro.remaining() < self.min_eval:
            self.reason = f"budget: remaining {self.a.ro.remaining()} < smallest evaluation {self.min_eval}"
        elif (self.lm.total_tokens_in + self.lm.total_tokens_out) >= OPT_TOKEN_CAP:
            self.reason = f"optimizer_token_cap {OPT_TOKEN_CAP}"
        elif self.consecutive_errors >= MAX_CONSECUTIVE_ERRORS:
            self.reason = f"{self.consecutive_errors} consecutive iteration errors"
        return self.reason is not None

    # callback side
    def on_error(self, ev):
        self._err_this_iter = True

    def on_iteration_end(self, ev):
        self.consecutive_errors = self.consecutive_errors + 1 if self._err_this_iter else 0
        self._err_this_iter = False


class Recorder:
    def __init__(self, events):
        self.events = events
        self.accepted = 0
        self.rejected = 0

    def on_proposal_end(self, ev):
        self.events({"event": "proposal", "iteration": ev["iteration"], "components": list(ev["new_instructions"]),
                     "new_texts": ev["new_instructions"], "prompts": ev["prompts"],
                     "raw_lm_outputs": ev["raw_lm_outputs"]}, stream="reflection_log.jsonl")

    def on_candidate_accepted(self, ev):
        self.accepted += 1
        self.events({"event": "accepted", **{k: ev[k] for k in ("iteration", "new_candidate_idx", "new_score")}})

    def on_candidate_rejected(self, ev):
        self.rejected += 1
        self.events({"event": "rejected", **{k: ev[k] for k in ("iteration", "old_score", "new_score", "reason")}})

    def on_valset_evaluated(self, ev):
        self.events({"event": "valset", "iteration": ev["iteration"], "candidate_idx": ev["candidate_idx"],
                     "average_score": ev["average_score"], "scores_by_val_id": ev["scores_by_val_id"],
                     "is_best_program": ev["is_best_program"]})

    def on_error(self, ev):
        self.events({"event": "error", "iteration": ev["iteration"], "exception": repr(ev["exception"])[:2000]})


