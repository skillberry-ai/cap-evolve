def seed_candidate(first: str | None = None) -> dict:
    cand = {"prompt.md": (SEED_DIR / "prompt.md").read_bytes().decode("utf-8"),
            "task_template.md": (SEED_DIR / "task_template.md").read_bytes().decode("utf-8"),
            SKILL: (SEED_DIR / SKILL).read_bytes().decode("utf-8")}
    for s in SCRIPT_SLOTS:
        assert not (SEED_DIR / s).exists(), s
        cand[s] = ""
    if first:  # smoke only: which component the round-robin selector visits first (GEPA starts at index 0)
        assert first in cand, first
        cand = {first: cand[first], **{k: v for k, v in cand.items() if k != first}}
    return cand


def script_index(cand: dict) -> str:
    """Deterministic API index of the non-empty script slots: import line, public signatures, docstring line 1."""
    out = []
    for s in SCRIPT_SLOTS:
        src = cand.get(s, "")
        if not src.strip():
            continue
        mod = Path(s).stem
        out.append(f"- `from skills.spreadsheet_helpers import {mod}`")
        try:
            tree = ast.parse(src)
        except SyntaxError as e:
            out.append(f"  - (module does not parse: {e.msg})")
            continue
        for node in tree.body:
            if isinstance(node, (ast.FunctionDef, ast.ClassDef)) and not node.name.startswith("_"):
                sig = f"{node.name}({ast.unparse(node.args)})" if isinstance(node, ast.FunctionDef) else \
                    f"class {node.name}"
                doc = (ast.get_docstring(node) or "").strip().splitlines()
                out.append(f"  - `{mod}.{sig}`" + (f": {doc[0]}" if doc else ""))
    return "\n".join(out)


def materialize(cand: dict, root: Path) -> Path:
    """Content-addressed candidate dir. The seed materializes byte-identical to seed_capability_v2."""
    key = hashlib.sha256(json.dumps(sorted(cand.items())).encode()).hexdigest()[:16]
    d = root / key
    if (d / ".complete").exists():
        return d
    tmp = root / f".{key}.tmp{os.getpid()}"
    shutil.rmtree(tmp, ignore_errors=True)
    shutil.copytree(SEED_DIR, tmp)
    for name, text in cand.items():
        p = tmp / name
        if name in SCRIPT_SLOTS:
            if text.strip():
                p.write_bytes(text.encode("utf-8"))
            continue
        p.write_bytes(text.encode("utf-8"))
    idx = script_index(cand)
    if idx:  # deviation D3: make new helpers visible to the agent without waiting for a SKILL.md step
        sk = tmp / SKILL
        sk.write_bytes((sk.read_bytes().decode("utf-8").rstrip() + "\n\n" + INDEX_HEADER + "\n" + idx + "\n").encode())
    (tmp / ".complete").write_text(key)
    shutil.rmtree(d, ignore_errors=True)
    tmp.rename(d)
    # `.complete` is harness bookkeeping, not a capability file; skills_tree_problems ignores the candidate root.
    return d


def tree_sha256(d: Path) -> dict:
    return {p.relative_to(d).as_posix(): hashlib.sha256(p.read_bytes()).hexdigest()
            for p in sorted(d.rglob("*")) if p.is_file() and p.name != ".complete"}


