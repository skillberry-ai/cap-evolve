# The GEPAAdapter: evaluate() = the common rollout, k=3 inside the call.
# ---------------------------------------------------------------------------------------------------------------
def _render_trace(trace, err: str | None) -> str:
    if not trace:
        return f"(no transcript: the rollout did not run{': ' + err if err else ''})"
    parts = []
    for m in trace:
        role = m.get("role", "?") if isinstance(m, dict) else "?"
        if role == "system":
            continue  # = this candidate's prompt.md + SKILL.md, already shown to the reflector
        content = m.get("content") if isinstance(m, dict) else m
        if isinstance(content, list):
            content = "\n".join(str(c.get("text", c)) if isinstance(c, dict) else str(c) for c in content)
        parts.append(f"[{role}]\n{content}")
    s = "\n\n".join(parts)
    if len(s) > TRACE_CHARS:
        head, tail = 6_000, TRACE_CHARS - 6_000 - 60
        s = s[:head] + f"\n\n...[{len(s) - head - tail} characters omitted]...\n\n" + s[-tail:]
    return s


def _is_infra(feedback: str, err) -> bool:
    # TaskResult does not expose the per-trial error_kind; a trial still infra after all retries carries the
    # adapter's infra feedback and no candidate error (see common_changes_needed in the report).
    return err is None and isinstance(feedback, str) and feedback.startswith("Rollout failed:")


class GepaFullAdapter:
    propose_new_texts = None  # use GEPA's own reflective proposer

    def __init__(self, ro: CommonRollout, run_dir: Path, tasks: dict, events):
        self.ro, self.run_dir, self.tasks, self.events = ro, run_dir, tasks, events
        self.cand_root = run_dir / "candidates"
        self.cand_root.mkdir(parents=True, exist_ok=True)
        self.budget_hit: str | None = None
        self.infra_retries = 0
        self.infra_missing = 0
        self.n_evals = 0

    def evaluate(self, batch, candidate, capture_traces=False):
        ids = [x["id"] for x in batch]
        uniq = list(dict.fromkeys(ids))  # GEPA pads small minibatches with repeats; never run an id twice
        cdir = materialize(candidate, self.cand_root)
        try:
            res = self.ro.evaluate(cdir, uniq, k=K, candidate_id=cdir.name)
        except BudgetStop as e:
            self.budget_hit = str(e)
            self.events({"event": "budget_stop", "detail": str(e), "spent": self.ro.spent, "R": self.ro.R})
            raise
        self.n_evals += 1
        self.infra_retries += res.infra_retries
        per = {}
        for t in uniq:
            tr = res.per_task[t]
            ok = [s for s, fb, er in zip(tr.trials, tr.feedback, tr.errors) if not _is_infra(fb, er)]
            self.infra_missing += len(tr.trials) - len(ok)
            per[t] = (sum(ok) / len(ok)) if ok else 0.0
        self.events({"event": "evaluate", "eval_call": res.eval_call, "candidate": cdir.name, "n_tasks": len(uniq),
                     "counted": res.counted, "infra_retries": res.infra_retries, "mean": sum(per.values()) / len(per),
                     "per_task": per, "capture_traces": capture_traces, "spent": self.ro.spent})
        scores = [per[t] for t in ids]
        outputs = [{"candidate": cdir.name, "mean": per[t], "trials": res.per_task[t].trials} for t in ids]
        trajs = None
        if capture_traces:
            trajs = []
            for t in ids:
                tr = res.per_task[t]
                j = min(range(len(tr.trials)), key=lambda i: (tr.trials[i], -i)) if tr.trials else 0
                err = tr.errors[j] if tr.errors else None
                fb = (f"CANDIDATE ERROR (this candidate's own fault, not infrastructure): {err}" if err
                      else (tr.feedback[j] if tr.feedback else ""))
                trajs.append({"id": t, "task": self.tasks[t], "mean": per[t], "trials": list(tr.trials),
                              "feedback": fb, "trace": _render_trace(tr.worst_trace, err)})
        return EvaluationBatch(outputs=outputs, scores=scores, trajectories=trajs, num_metric_calls=len(uniq) * K)

    def make_reflective_dataset(self, candidate, eval_batch, components_to_update):
        rows, seen = [], set()
        for tj in eval_batch.trajectories or []:
            if tj["id"] in seen:  # a padded minibatch repeats an id; one row per task
                continue
            seen.add(tj["id"])
            t = tj["task"]
            rows.append({
                "Inputs": {"instruction": t["instruction"][:4000], "instruction_type": t["instruction_type"],
                           "answer_position": t["answer_position"]},
                "Generated Outputs": tj["trace"],
                "Feedback": (f"Mean score {tj['mean']:.2f} over {len(tj['trials'])} trials "
                             f"(per-trial hard pass: {tj['trials']}). The transcript above is the lowest-scoring "
                             f"trial. Grader feedback on it: {tj['feedback']}"),
            })
        out = {}
        for comp in components_to_update:
            recs = [dict(r) for r in rows]
            if recs:
                ctx = {k: v for k, v in candidate.items() if k != comp and k not in SCRIPT_SLOTS}
                idx = script_index(candidate)
                recs[0] = {"Other files of the same candidate (read-only context; edit only the file above)":
                           {**ctx, "helper scripts (API index)": idx or "(no helper scripts exist yet)"}, **recs[0]}
            out[comp] = recs
        return out


