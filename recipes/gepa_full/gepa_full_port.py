def reflection_templates() -> dict:
    t = {"prompt.md": TEXT_TEMPLATE, "task_template.md": TEMPLATE_TEMPLATE, SKILL: SKILL_TEMPLATE}
    t.update({s: SCRIPT_TEMPLATE for s in SCRIPT_SLOTS})
    for v in t.values():
        InstructionProposalSignature.validate_prompt_template(v)
    return t


