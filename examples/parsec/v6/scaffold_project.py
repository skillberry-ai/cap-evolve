#!/usr/bin/env python3
"""Scaffold the single v6 cap-evolve project: one shared bundle, optimized jointly over F, gated on C.

    .capevolve/v6_<suite>/project/
      seed_capability/*.md     the 8 prompt files the search starts from
      capevolve.yaml           hill-climb + split_mode: pooled + promotion_rule: P2
      split_ids.json           feedback / confirm / test (from make_split.py)
      public_tasks.txt         F, for the dispatching adapter's transcript routing
      adapters  -> examples/parsec/v6/adapters     (the dispatcher)
      optimizer -> examples/parsec/v6/optimizer   (multi-task, generalization-aware)

``--seed-artifact`` is verified byte-for-byte against ``--expect`` (a directory of the
same 8 files, e.g. a checkout of parsec-history's artifacts/v5/seed) when given:
a run seeded from the wrong bundle is the failure v5_t1_e1 was discarded for.

Usage:
    python3 examples/parsec/v6/scaffold_project.py --suite-id g2_e1 \\
        --seed-artifact <dir> --split-dir <make_split.py --out dir> [--expect <dir>] [--force]
"""
from __future__ import annotations

import argparse
import filecmp
import os
import shutil
import sys
from pathlib import Path

V6_DIR = Path(__file__).resolve().parent
REPO_ROOT = V6_DIR.parents[2]
PROMPT_FILES = ["orchestrator.md", "shared_context.md", "aap2_agent.md", "babylon_agent.md",
                "cost_agent.md", "icinga_agent.md", "ocpv_agent.md", "security_agent.md"]

# Every knob that decides cost or acceptance is spelled out, even where it equals cap-evolve's
# default, so the recipe is the whole record of what ran.
SPEC = """\
# v6 {suite}: one shared bundle, optimized on F, accepted only on the hidden C. See README.md.
# Generated by examples/parsec/v6/scaffold_project.py; edits are overwritten with --force.
optimizer_skill: claude-code
optimizer_model: claude-opus-5
algorithm_skill: hill-climb
target_model: claude-sonnet-4-6
capabilities: [system-prompt]
split_ids_file: split_ids.json
split_mode: pooled
promotion_rule: P2
num_trials: {num_trials}
p2_incumbent_trials: {incumbent_trials}
p2_rung_sizes: [{rung1}, {rung2}]
p2_ctrl_m: {ctrl_m}
p2_conf_n: {conf_n}
p2_gs_looks: [{looks}]
p2_dmin: 0.02
max_iterations: {max_iterations}
stall: {stall}
max_usd: {max_usd}
max_optimizer_usd: {max_optimizer_usd}
finalize: false
dashboard: auto
"""


def link(path: Path, target: Path) -> None:
    rel = Path(os.path.relpath(target, start=path.parent))
    if path.is_symlink() or path.exists():
        if path.resolve() != target.resolve():
            raise RuntimeError(f"{path} exists and does not point at {target}")
        return
    path.symlink_to(rel, target_is_directory=True)


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--suite-id", required=True)
    ap.add_argument("--seed-artifact", required=True, type=Path)
    ap.add_argument("--split-dir", required=True, type=Path)
    ap.add_argument("--expect", type=Path, help="directory the seed must match byte for byte")
    ap.add_argument("--num-trials", type=int, default=10)
    ap.add_argument("--incumbent-trials", type=int, default=4)
    ap.add_argument("--rung1", type=int, default=12)
    ap.add_argument("--rung2", type=int, default=36)
    ap.add_argument("--ctrl-m", type=int, default=4)
    ap.add_argument("--conf-n", type=int, default=147)
    ap.add_argument("--looks", default="12, 24, 49, 98, 147")
    ap.add_argument("--max-iterations", type=int, default=10)
    ap.add_argument("--stall", type=int, default=2)
    ap.add_argument("--max-usd", type=float, default=2500.0)
    ap.add_argument("--max-optimizer-usd", type=float, default=600.0)
    ap.add_argument("--force", action="store_true")
    args = ap.parse_args()

    missing = [n for n in PROMPT_FILES if not (args.seed_artifact / n).is_file()]
    if missing:
        print(f"seed artifact lacks {missing}", file=sys.stderr)
        return 2
    if args.expect is not None:
        differ = [n for n in PROMPT_FILES
                  if not filecmp.cmp(args.seed_artifact / n, args.expect / n, shallow=False)]
        if differ:
            print(f"seed artifact differs from {args.expect} in {differ}; refusing to scaffold", file=sys.stderr)
            return 2
    for f in ("split_ids.json", "public_tasks.txt"):
        if not (args.split_dir / f).is_file():
            print(f"{args.split_dir / f} missing — run make_split.py first", file=sys.stderr)
            return 2
    if int(args.looks.split(",")[-1]) != args.conf_n:
        print("the last of --looks must equal --conf-n", file=sys.stderr)
        return 2

    proj = REPO_ROOT / ".capevolve" / f"v6_{args.suite_id}" / "project"
    spec = proj / "capevolve.yaml"
    if spec.exists() and not args.force:
        print(f"{spec} exists; pass --force to rewrite the project files", file=sys.stderr)
        return 2
    seed = proj / "seed_capability"
    seed.mkdir(parents=True, exist_ok=True)
    for n in PROMPT_FILES:
        shutil.copyfile(args.seed_artifact / n, seed / n)
    for f in ("split_ids.json", "public_tasks.txt"):
        shutil.copyfile(args.split_dir / f, proj / f)
    spec.write_text(SPEC.format(suite=args.suite_id, num_trials=args.num_trials,
                                incumbent_trials=args.incumbent_trials, rung1=args.rung1, rung2=args.rung2,
                                ctrl_m=args.ctrl_m, conf_n=args.conf_n, looks=args.looks,
                                max_iterations=args.max_iterations, stall=args.stall, max_usd=args.max_usd,
                                max_optimizer_usd=args.max_optimizer_usd), encoding="utf-8")
    link(proj / "adapters", V6_DIR / "adapters")
    # v6's own copy, not examples/parsec/optimizer: that one tells the optimizer "there
    # is no cross-task generalization question this round" (true for v4_t2_e1/h4's
    # single-task projects, false here) and is still used by those arms unchanged.
    link(proj / "optimizer", V6_DIR / "optimizer")
    print(f"scaffolded {proj}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
