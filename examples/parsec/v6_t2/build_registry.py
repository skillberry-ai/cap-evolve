#!/usr/bin/env python3
"""Regenerate examples/parsec/v6_t2/registry.yaml: the stock optimizer registry with ONE change.

The `claude-code` row's executable is swapped for claude_t2.sh, which stages the last rejected
candidate's trials and then execs `claude` with the same arguments. The row keeps its NAME on
purpose: cap-evolve's harness reads the stock registry by optimizer name to place native skills
(`.claude/skills`), write `CLAUDE.md`, copy the optimizer reference, and decide the parallel
fan-out note. Under the same name the v6_t2 optimizer gets exactly the context v6_g2's did; only
`run-optimizer`, pointed here by CAPEVOLVE_OPTIMIZER_REGISTRY, sees the swapped command.
"""
from __future__ import annotations

from pathlib import Path

T2_DIR = Path(__file__).resolve().parent
STOCK = T2_DIR.parents[2] / "skills" / "optimizers" / "registry.yaml"
OLD = 'command_template: "claude -p'
NEW = 'command_template: "${V6_T2_DIR}/claude_t2.sh -p'
HEADER = """\
# v6_t2 optimizer registry. GENERATED by examples/parsec/v6_t2/build_registry.py from
# skills/optimizers/registry.yaml; regenerate it whenever the stock registry changes.
# One difference from the stock file: the claude-code row runs claude_t2.sh (stage_rejected.py,
# then `claude` with the same arguments). run_t2.sh points CAPEVOLVE_OPTIMIZER_REGISTRY here.

"""


def main() -> int:
    reg = STOCK.read_text(encoding="utf-8")
    start = reg.index("\nclaude-code:\n")
    at = reg.index(OLD, start)
    if reg.count(OLD) != 1 or at > reg.find("\n\n", start + 1):
        raise SystemExit("stock claude-code command_template changed shape; update build_registry.py")
    (T2_DIR / "registry.yaml").write_text(HEADER + reg[:at] + NEW + reg[at + len(OLD):], encoding="utf-8")
    print(f"wrote {T2_DIR / 'registry.yaml'}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
