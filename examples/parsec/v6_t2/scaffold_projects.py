#!/usr/bin/env python3
"""Scaffold the v6 task-by-task (T2) projects: one single-task cap-evolve project per task.

    .capevolve/v6_t2_<suite>_<task>/project/
      seed_capability/*.md     the 8 prompt files, byte-identical to v6_g2_e1's seed
      capevolve.yaml           hill-climb on one task; reuse_baseline -> prior/ below
      split_ids.json           train = val = test = [task]
      public_tasks.txt         [task]: its transcripts are the optimizer's to read
      adapters  -> examples/parsec/v6/adapters     (the v6 dispatcher, unchanged)
      optimizer -> examples/parsec/v6_t2/optimizer (single-task brief, merge-aware)
    .capevolve/v6_t2_<suite>_<task>/prior/
      a minimal "prior run" holding the Seed's ten v6_g2_e1 feedback trials of this task,
      as rollouts/val/<task>__seed__t0..9.json + baseline.json + splits.json, so the
      run's --reuse-baseline starts from them instead of re-running the Seed.

The Seed trials are copied, never re-scored: they are v6_g2_e1's own Seed sweep on the
feedback split, the same evidence the Global optimizer read about this task.

Usage:
    python3 examples/parsec/v6_t2/scaffold_projects.py --suite-id e1 \\
        --seed-artifact <dir> --g2-run <v6_g2_e1 run dir> [--expect <dir>] [--only TASK] [--force]
"""
from __future__ import annotations

import argparse
import filecmp
import json
import os
import shutil
import sys
from pathlib import Path

T2_DIR = Path(__file__).resolve().parent
V6_DIR = T2_DIR.parent / "v6"
REPO_ROOT = T2_DIR.parents[2]
PROMPT_FILES = ["orchestrator.md", "shared_context.md", "aap2_agent.md", "babylon_agent.md",
                "cost_agent.md", "icinga_agent.md", "ocpv_agent.md", "security_agent.md"]

# The ten lowest-scoring feedback tasks under the Seed that the fast-path router does not send
# to a specialist lacking a required tool (see PLAN.md for the exclusions and their reasons).
TASK_IDS = [
    "platform-158-lab-instances-outside-default-region",
    "cloud-057-cloudtrail-select-only-refusal",
    "platform-121-near-miss-pick-partner-repo",
    "cloud-058-malformed-account-id",
    "cost-407-aws-historical-query-came-back-org-wide",
    "platform-116-timeout-headroom-from-history",
    "icinga-215-ack-comment-author-and-expiry",
    "icinga-204-downtime-window-expired",
    "cost-408-three-cloud-total-gcp-query-failed",
    "platform-004-events-then-config",
]
SEED_TRIALS = 10

# Every knob that decides cost or acceptance is spelled out, even where it equals cap-evolve's
# default, so the recipe is the whole record of what ran.
SPEC = """\
# v6_t2 {suite}: single-task optimization of {task}. See examples/parsec/v6_t2/PLAN.md.
# Generated by examples/parsec/v6_t2/scaffold_projects.py; edits are overwritten with --force.
optimizer_skill: claude-code
optimizer_model: claude-opus-5
algorithm_skill: hill-climb
target_model: claude-sonnet-4-6
capabilities: [system-prompt]
split_ids_file: split_ids.json
reuse_baseline: {prior}
num_trials: {num_trials}
max_iterations: {max_iterations}
stall: {stall}
max_usd: {max_usd}
max_optimizer_usd: {max_optimizer_usd}
stop_at_reward: 1.0
finalize: false
dashboard: off
"""


def link(path: Path, target: Path) -> None:
    rel = Path(os.path.relpath(target, start=path.parent))
    if path.is_symlink() or path.exists():
        if path.resolve() != target.resolve():
            raise RuntimeError(f"{path} exists and does not point at {target}")
        return
    path.symlink_to(rel, target_is_directory=True)


def build_prior(prior: Path, task: str, g2_run: Path) -> float:
    """Write the minimal prior run that ``reuse_baseline`` reads; return the Seed's mean reward."""
    src = sorted((g2_run / "rollouts" / "feedback").glob(f"{task}__seed__t*.json"))
    if len(src) != SEED_TRIALS:
        raise RuntimeError(f"{task}: expected {SEED_TRIALS} Seed feedback trials in {g2_run}, found {len(src)}")
    val = prior / "rollouts" / "val"
    if val.exists():
        shutil.rmtree(val)
    val.mkdir(parents=True)
    rewards = []
    for f in src:
        rec = json.loads(f.read_text(encoding="utf-8"))
        if (rec.get("rollout") or {}).get("error"):
            raise RuntimeError(f"{f.name}: an errored Seed trial; refusing to reuse it as a baseline")
        rewards.append(float(rec["score"]["reward"]))
        shutil.copyfile(f, val / f.name)
    shutil.copytree(g2_run / "candidates" / "seed", prior / "candidates" / "seed", dirs_exist_ok=True)
    (prior / "splits.json").write_text(json.dumps({"train": [task], "val": [task], "test": [task],
                                                   "seed": 0, "test_used": False}, indent=2), encoding="utf-8")
    # baseline.json is computed by cap-evolve's own resume reader from the copied trials, so the
    # reused baseline is exactly what the run would have recorded had it measured these trials itself.
    sys.path.insert(0, str(REPO_ROOT / "core"))
    from cap_evolve.harness import split_result_from_rollouts
    from cap_evolve.rundir import RunDir
    result = split_result_from_rollouts(RunDir(prior), "seed", "val")
    if abs(result.reward - sum(rewards) / len(rewards)) > 1e-9:
        raise RuntimeError(f"{task}: reconstructed Seed reward {result.reward} != trial mean")
    (prior / "baseline.json").write_text(json.dumps({"val": result.to_dict(), "best_id": "seed", "split": "val",
                                                     "reused_from": str(g2_run)}, indent=2), encoding="utf-8")
    return result.reward


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--suite-id", required=True)
    ap.add_argument("--seed-artifact", required=True, type=Path)
    ap.add_argument("--g2-run", required=True, type=Path, help="the v6_g2_e1 run dir whose Seed trials to reuse")
    ap.add_argument("--expect", type=Path, help="directory the seed must match byte for byte")
    ap.add_argument("--only", action="append", help="scaffold only this task (repeatable)")
    ap.add_argument("--num-trials", type=int, default=5)
    ap.add_argument("--max-iterations", type=int, default=5)
    ap.add_argument("--stall", type=int, default=2)
    ap.add_argument("--max-usd", type=float, default=50.0)
    ap.add_argument("--max-optimizer-usd", type=float, default=20.0)
    ap.add_argument("--force", action="store_true")
    args = ap.parse_args()

    tasks = args.only or TASK_IDS
    unknown = [t for t in tasks if t not in TASK_IDS]
    if unknown:
        print(f"unknown task id(s): {unknown}", file=sys.stderr)
        return 2
    missing = [n for n in PROMPT_FILES if not (args.seed_artifact / n).is_file()]
    if missing:
        print(f"seed artifact lacks {missing}", file=sys.stderr)
        return 2
    g2_seed = args.g2_run / "candidates" / "seed"
    for ref in [p for p in (args.expect, g2_seed) if p is not None]:
        differ = [n for n in PROMPT_FILES if not filecmp.cmp(args.seed_artifact / n, ref / n, shallow=False)]
        if differ:
            print(f"seed artifact differs from {ref} in {differ}; refusing to scaffold", file=sys.stderr)
            return 2

    for task in tasks:
        root = REPO_ROOT / ".capevolve" / f"v6_t2_{args.suite_id}_{task}"
        proj, prior = root / "project", root / "prior"
        spec = proj / "capevolve.yaml"
        if spec.exists() and not args.force:
            print(f"{spec} exists; pass --force to rewrite the project files", file=sys.stderr)
            return 2
        seed = proj / "seed_capability"
        seed.mkdir(parents=True, exist_ok=True)
        for n in PROMPT_FILES:
            shutil.copyfile(args.seed_artifact / n, seed / n)
        (proj / "split_ids.json").write_text(json.dumps({"train": [task], "val": [task], "test": [task]},
                                                        indent=2) + "\n", encoding="utf-8")
        (proj / "public_tasks.txt").write_text(task + "\n", encoding="utf-8")
        seed_mean = build_prior(prior, task, args.g2_run)
        spec.write_text(SPEC.format(suite=args.suite_id, task=task, prior=prior, num_trials=args.num_trials,
                                    max_iterations=args.max_iterations, stall=args.stall,
                                    max_usd=args.max_usd, max_optimizer_usd=args.max_optimizer_usd),
                        encoding="utf-8")
        link(proj / "adapters", V6_DIR / "adapters")
        link(proj / "optimizer", T2_DIR / "optimizer")
        print(f"scaffolded {proj}  (Seed {seed_mean:.3f} over {SEED_TRIALS} reused trials)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
