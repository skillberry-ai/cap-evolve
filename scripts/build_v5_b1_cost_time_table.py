#!/usr/bin/env python3
"""Build results/v5/v5_b1_e1/cost_time/v5_b1_e1_results_table.md from
results/v5/v5_b1_e1/results.json.

Mirrors v4_t4_e1_results_table.md's shape (one zero-shot eval per task, no
optimizer stage), with two columns v4's table did not carry -- `spread` and
`sd` -- because this arm's job includes characterising how stochastic the
benchmark is, and a mean alone hides that.

Unlike v4, this table is DERIVED from results.json rather than being the
vendored upstream source parsed into it: v5 has no upstream collect script
in this branch, so results.json is the single source of truth and this file
is a human-readable rendering of it.

Usage: python3 scripts/build_v5_b1_cost_time_table.py [--check]
  --check   exit 1 if regenerating would change the table, instead of writing it.
"""
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
RESULTS_JSON = ROOT / "results" / "v5" / "v5_b1_e1" / "results.json"
TABLE_MD = ROOT / "results" / "v5" / "v5_b1_e1" / "cost_time" / "v5_b1_e1_results_table.md"


def render(results):
    ledger = results["task_ledger"]
    o = results["sections"]["overall"]

    L = []
    L.append("# v5_b1_e1 -- baseline (original skill) zero-shot sweep: cost & time")
    L.append("")
    L.append(
        "One row per task -- each task is exactly ONE baseline eval (5 trials), zero-shot, "
        "no optimization step. Generated by "
        "[`scripts/build_v5_b1_cost_time_table.py`](../../../../scripts/build_v5_b1_cost_time_table.py) "
        "from [`../results.json`](../results.json)."
    )
    L.append("")
    L.append(
        f"**{len(ledger)}/{len(ledger)} tasks done, 0 errored trials.** "
        f"Cost: ${o['cost_usd']:,.2f}. Tokens: {o['tokens']:,}. "
        f"Summed task time: {o['seconds']/60:.1f} min ({o['seconds']/3600:.2f} hr) -- "
        f"summed across tasks; the sweep ran at 10-way concurrency on CCC/LSF, so elapsed "
        f"wall-clock was far less (see `recipes/v5/v5_b1_e1/README.md`)."
    )
    L.append("")
    L.append(
        f"`spread` = max - min across the 5 trials, `sd` = population sd. "
        f"**{o['n_variable']} of {len(ledger)} tasks ({o['pct_variable']:.1f}%) are "
        f"non-deterministic**; see `../summary.md` for what that bounds."
    )
    L.append("")
    L.append("## Summary table")
    L.append("")
    L.append("| # | Task | set | Reward(val) | stderr | Trial rewards | spread | sd "
             "| Errored | Headroom | Cost($) | Tokens | Time(s) |")
    L.append("|---|---|:--|---|---|---|---|---|---|---|---|---|---|")
    for i, r in enumerate(ledger, 1):
        trials = ", ".join(f"{v:.3f}" for v in (r["trial_rewards"] or []))
        L.append(
            f"| {i} | {r['task']} | {r['task_set']} | {r['reward']:.4f} | {r['stderr']:.4f} "
            f"| {trials} | {r['spread']:.3f} | {r['sd']:.3f} | {r['errored_trials']} "
            f"| {r['headroom']} | {r['cost_usd']:.4f} | {r['tokens']:,} | {r['seconds']:.1f} |"
        )
    L.append("")
    return "\n".join(L)


def main():
    check_only = "--check" in sys.argv
    results = json.loads(RESULTS_JSON.read_text())
    new_text = render(results)
    old_text = TABLE_MD.read_text() if TABLE_MD.exists() else None

    if old_text == new_text:
        print("v5_b1_e1_results_table.md already up to date.")
        return 0
    if check_only:
        print("v5_b1_e1_results_table.md is STALE relative to results.json.", file=sys.stderr)
        return 1

    TABLE_MD.parent.mkdir(parents=True, exist_ok=True)
    TABLE_MD.write_text(new_text)
    print(f"Wrote {TABLE_MD.relative_to(ROOT)} ({len(results['task_ledger'])} tasks).")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
