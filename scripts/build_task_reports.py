#!/usr/bin/env python3
"""Generate/refresh the per-task reports under reports/task-by-task/.

One report per task row in results/results.json — 30 for v1, 10 for v2. Each report is level 3
of the drill-down: level 1 is the dashboard row on `benchmark-history`, level 2 is
ui/heatmap.html, level 3 is "what did we change on this task, what worked, what didn't, and
what can we actually learn from it".

Each file is split by markers:

    <!-- BEGIN:auto ... -->   numbers, contract shape, provenance, links   <!-- END:auto -->

    ## What changed / ## What worked / ## What didn't / ## What we can (or can't) learn

Re-running rewrites ONLY the auto block of an existing file and never touches a byte outside
it. The reason for the split is that transcribed numbers drift — on the sibling
skillsbench-history branch that drift produced a heatmap that undercounted its own pass rate
and a summary.md quoting a mean that was never measured. Numbers stay derived; narrative stays
human.

Two things differ from skillsbench-history's version of this script, both because parsec's data
is shaped differently, and both deliberate:

  1. **The measurement table is vertical, not horizontal.** skillsbench could put
     seed/cand_0001/cand_0002/best in one row of columns because every cell there was measured
     at the same trial count. Parsec's are not: v1's baseline sweep is n=1 and its pilot is
     n=30; v2's `seed` is a *reused* n=3 measurement while everything else in that run is n=9.
     A horizontal row would silently invite comparing an n=3 number with an n=9 number, which
     is precisely the mistake that produced v2's headline. So every number gets its own row,
     with its `n` and its split beside it.

  2. **Narrative is pre-filled for more classes.** skillsbench pre-filled three (saturated,
     infra-failed, no-signal); here every v1 task whose story is fully determined by its own
     contract and baseline row ships written rather than as a placeholder, because for 28 of
     the 30 v1 tasks the optimizer never ran and "what happened" genuinely is the contract plus
     one trial. Placeholders are left only where a human has to read a journal to say anything
     true. `--stats` reports how many remain.

Usage:
  python3 scripts/build_task_reports.py            # create missing, refresh auto blocks
  python3 scripts/build_task_reports.py --check    # exit 1 if anything would change
  python3 scripts/build_task_reports.py --stats    # coverage report, write nothing
"""
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
RESULTS_JSON = ROOT / "results" / "results.json"
REPORTS_DIR = ROOT / "reports" / "task-by-task"

AUTO_BEGIN = "<!-- BEGIN:auto — regenerated by scripts/build_task_reports.py; do not hand-edit inside this block -->"
AUTO_END = "<!-- END:auto -->"
PLACEHOLDER = "_Not yet analysed._"

AUTO_BLOCK_RE = re.compile(re.escape(AUTO_BEGIN) + r".*?" + re.escape(AUTO_END), re.DOTALL)

# Depth from reports/task-by-task/<file>.md back to the branch root.
UP = "../.."


def fmt(v):
    return "—" if v is None else f"{v:.3f}"


def fmtd(v):
    if v is None:
        return "—"
    return f"{'+' if v >= 0 else ''}{v:.3f}"


def experiment_of(results: dict, exp: str) -> dict:
    return next(e for e in results["experiments"] if e["experiment"] == exp)


def run_of(results: dict, exp: str) -> dict:
    return next(r for r in results["runs"] if r["experiment"] == exp and r["headline"])


# --------------------------------------------------------------------------- auto block


def measurement_rows(t: dict, run: dict) -> list[tuple]:
    """(label, split, n, reward, note) — one row per distinct measurement of this task.

    Ordered oldest-instrument-first: the n=1 sweep, then whatever the pilot measured. Rows the
    run did not produce are omitted rather than shown as `—`, so the table's length is itself
    information: a 1-row table means this task was measured exactly once, ever.
    """
    rows = [(
        "baseline sweep",
        "all",
        t["baseline_n"],
        t["baseline"],
        "single trial, no optimizer — `" + run["experiment"] + "` reference sweep",
    )]
    if t["status"] != "OPTIMIZED":
        return rows

    if t.get("seed") is not None:
        note = "cap-evolve baseline on val"
        if run.get("baseline_reused"):
            note = (
                "cap-evolve baseline on val — **reused** from `"
                + run["baseline_reused"]["prior_run_dir"]
                + "`, not re-measured in this run"
            )
        rows.append(("`seed`", "val", t.get("seed_n"), t.get("seed"), note))
        if t.get("seed_all") is not None and t.get("seed_all") != t.get("seed"):
            rows.append((
                "`seed` (errored trials as 0.0)", "val", t.get("seed_n"), t.get("seed_all"),
                "same trials, other denominator",
            ))
    if t.get("seed_train") is not None:
        rows.append((
            "`seed_train`", "train", t.get("seed_train_n"), t.get("seed_train"),
            "the seed re-measured inside the iteration, at the iteration's trial count",
        ))
        if t.get("seed_train_all") is not None and t.get("seed_train_all") != t.get("seed_train"):
            rows.append((
                "`seed_train` (errored trials as 0.0)", "train", t.get("seed_train_n"),
                t.get("seed_train_all"),
                "same trials, other denominator — **this is the convention cap-evolve printed for v2**"
                if t["experiment"] == "v2" else "same trials, other denominator",
            ))
    for key, label in (("cand_0001", "`cand_0001`"), ("cand_0002", "`cand_0002`")):
        if t.get(key) is not None:
            split = "train" if t["experiment"] == "v2" else "val"
            n = t.get("seed_train_n") if t["experiment"] == "v2" else t.get("seed_n")
            verdict = "**accepted champion**" if t.get("best_tag") == key else "rejected"
            rows.append((label, split, n, t.get(key), verdict))
    if t.get("final_test") is not None:
        note = "sealed-test evaluation"
        if run.get("test_holdout") == "overlaps-train-or-val":
            note = (
                "sealed-test evaluation — **NOT held out**: this run's `test` split equals its "
                "train/val split, so read it as a fit metric"
            )
        rows.append(("`FINAL` (test)", "test", None, t.get("final_test"), note))
    return rows


def tool_list(tools: list[str]) -> str:
    """`a`, `b` and `c` — Oxford-comma-free, because these appear mid-sentence in prose."""
    q = [f"`{x}`" for x in tools]
    if len(q) == 1:
        return q[0]
    return ", ".join(q[:-1]) + " and " + q[-1]


def no_sim_exposed(tools: list[str]) -> str:
    """The clause that follows tool_list(); agrees in number."""
    return (
        "which no simulator running on 2026-08-12 exposed"
        if len(tools) == 1
        else "none of which any simulator running on 2026-08-12 exposed"
    )


def contract_line(t: dict) -> str:
    if t["experiment"] == "v1":
        n_ops = t.get("n_trajectory_ops")
        n_assn = t.get("n_assertions")
        passed = t.get("baseline_assertions_passed")
        assn = (
            "**0 assertions** — an empty list scores a vacuous `assertions: 1.0`"
            if n_assn == 0
            else f"{n_assn} `answer_contains` assertion{'s' if n_assn != 1 else ''} "
            f"(**{passed if passed is not None else '?'} passed** at baseline)"
        )
        missing = t.get("trajectory_tools_missing_at_baseline") or []
        reach = (
            "\n\n**Trajectory reachability at baseline:** the contract demands "
            + tool_list(missing)
            + f", {no_sim_exposed(missing)}. Under a "
            f"`{t.get('trajectory_match')}` match one uncallable op fails the whole containment, "
            "so `trajectory: 1.0` was **unreachable by construction** on this task and its reward "
            "was capped at 0.5 whatever the skill said."
            if missing
            else "\n\n**Trajectory reachability at baseline:** every demanded op was callable "
            "against the two simulators running on 2026-08-12. Only 5 of the 30 v1 tasks are in "
            "this position, and all 5 matched the trajectory."
        )
        return (
            f"**Contract** (`tests/expected.json`): `{t.get('trajectory_match')}` match over "
            f"**{n_ops} demanded tool call{'s' if n_ops != 1 else ''}** · {assn} · "
            "weights trajectory 0.5 / assertions 0.5 · gate requires `status == ok` and a "
            "non-empty answer." + reach
        )
    w = t.get("weights") or {}
    nd = t.get("n_derived_facts") or 0
    return (
        f"**Contract** (`tests/expected.json`, schema `bench/v2`): "
        f"**{t.get('n_expected_calls')} expected tool call{'s' if t.get('n_expected_calls') != 1 else ''}** · "
        f"**{t.get('n_required_facts')} required answer fact{'s' if t.get('n_required_facts') != 1 else ''}**"
        + (f" ({nd} *derived* — not present anywhere in the seed data)" if nd else "")
        + f" · weights tool_calls {w.get('tool_calls')} / answer {w.get('answer')}."
    )


def build_auto_block(t: dict, results: dict) -> str:
    exp = t["experiment"]
    run = run_of(results, exp)
    es = experiment_of(results, exp)

    src = "trace-extracted from a production session" if exp == "v1" else "hand-authored"
    status = t["status"]

    head = (
        f"**Status:** `{status}` · **Experiment:** `{exp}` ({src}) · "
        f"**Category:** {t['category']} / {t['subcategory']}"
    )
    if t.get("headline_run"):
        head += f" · **Run:** `{t['headline_run']}`"

    lines = [AUTO_BEGIN, "", head, ""]

    if t.get("prompt"):
        lines += ["**Prompt given to the agent:**", "", "> " + t["prompt"], ""]

    lines += [contract_line(t), ""]

    if t.get("flags"):
        lines += ["**Flags:** " + " · ".join(f"`{f}`" for f in t["flags"]), ""]

    lines += [
        "| measurement | split | n | reward | |",
        "|---|---|--:|--:|---|",
    ]
    for label, split, n, reward, note in measurement_rows(t, run):
        lines.append(
            f"| {label} | `{split}` | {n if n is not None else '—'} | **{fmt(reward)}** | {note} |"
        )
    lines.append("")

    if status == "OPTIMIZED":
        lines.append(
            f"**Best:** `{t.get('best_tag')}` @ {fmt(t.get('best'))} · "
            f"**Δ vs `seed`:** {fmtd(t.get('delta'))} · "
            f"**Iterations spent (whole run):** {t.get('iters_spent')} · "
            f"**Harness-errored trials in this task's cells:** {t.get('trials_errored')}"
        )
    else:
        lines.append(
            "**The optimizer never ran on this task.** It was not in the pilot's `val` split, "
            f"so `seed`, `best`, `delta` and `final_test` are null by construction — not zero. "
            f"Only {es['n_optimized']} of {es['n_tasks']} {exp} tasks entered cap-evolve; the "
            "other rows are a one-trial reference sweep."
        )
    lines.append("")
    lines.append(
        "_Every number above is generated from [`results/results.json`]("
        + UP + "/results/results.json). Read no cell without the `n` beside it: this branch's "
        "central finding is that the same unchanged skill measures differently at different "
        "trial counts._"
    )
    lines += ["", "**Material:**"]

    mat = []
    if exp == "v1":
        mat.append(
            f"- [`results/v1/baseline_all_1786543049.json`]({UP}/results/v1/"
            "baseline_all_1786543049.json) — the n=1 sweep row this task's baseline comes from, "
            "with its `completion` / `trajectory` / `assertions` components"
        )
        mat.append(
            f"- [`results/v1/tasks.json`]({UP}/results/v1/tasks.json) — this task's full "
            "contract: the demanded tool-call sequence and every `answer_contains` string"
        )
    else:
        mat.append(
            f"- [`results/v2/tasks.json`]({UP}/results/v2/tasks.json) — this task's full "
            "contract: expected calls, required/derived/forbidden facts, per-task weights"
        )
        mat.append(
            f"- [`results/v2/per_task_scores.csv`]({UP}/results/v2/per_task_scores.csv) — the "
            "hand-maintained per-task analysis, including a note per task per iteration. "
            "**Its numbers use the errored-as-zero denominator**, so they can differ from the "
            "table above; compare like with like"
        )
    if t.get("headline_run"):
        rd = f"{UP}/results/{exp}/runs/{t['headline_run']}"
        mat.append(f"- [`{t['headline_run']}/report.md`]({rd}/report.md) — the run's own write-up")
        if (ROOT / "results" / exp / "runs" / t["headline_run"] / "JOURNAL.md").is_file():
            mat.append(
                f"- [`{t['headline_run']}/JOURNAL.md`]({rd}/JOURNAL.md) — per-iteration "
                "hypothesis, edit, and verdict, in the optimizer's own words"
            )
        mat.append(
            f"- [`{t['headline_run']}/events.jsonl`]({rd}/events.jsonl) — the split aggregates "
            "every number above was reconciled against"
        )
    mat.append(
        f"- [`results/{exp}/per_task_scores.json`]({UP}/results/{exp}/per_task_scores.json) — "
        "per-trial reward vectors for this task in every run of this experiment, with errored "
        "trials marked `null`"
    )
    if exp == "v1":
        mat.append(
            f"- [`artifacts/v1/seed/SKILL.md`]({UP}/artifacts/v1/seed/SKILL.md) and the two "
            f"[rejected candidates]({UP}/artifacts/v1/rejected/) — diff them to see what was "
            "tried and thrown away"
        )
    else:
        mat.append(
            f"- [`artifacts/v2/best/`]({UP}/artifacts/v2/best/) vs "
            f"[`artifacts/v2/seed/`]({UP}/artifacts/v2/seed/) — the accepted champion against "
            "the seed"
        )
    mat.append(f"- [`ui/heatmap.html`]({UP}/ui/heatmap.html) — this row in context of all "
               f"{results['total_tasks']} tasks")

    lines += mat
    lines += ["", AUTO_END]
    return "\n".join(lines)


