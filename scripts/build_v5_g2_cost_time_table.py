#!/usr/bin/env python3
"""Build results/v5/v5_g2_e1/cost_time/v5_g2_e1_results_table.md from
results/v5/v5_g2_e1/results.json.

Mirrors v5_b1_e1_results_table.md's shape, with a v5_b1 column (and delta)
in place of v4_t1/jb -- this arm's comparison is against the v5 baseline.

Usage: python3 scripts/build_v5_g2_cost_time_table.py [--check]
  --check   exit 1 if regenerating would change the table, instead of writing it.
"""
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
RESULTS_JSON = ROOT / "results" / "v5" / "v5_g2_e1" / "results.json"
TABLE_MD = ROOT / "results" / "v5" / "v5_g2_e1" / "cost_time" / "v5_g2_e1_results_table.md"


def render(results):
    ledger = results["task_ledger"]
    o = results["sections"]["overall"]

    L = []
    L.append("# v5_g2_e1 -- cand_0004 (v4's G2-arm champion) reused on all 136 v5 tasks: cost & time")
    L.append("")
    L.append(
        "One row per task -- each task is exactly ONE eval (5 trials), zero-shot reuse of "
        "`artifacts/v4/v4_g_e1/best`, no further optimization step. Generated by "
        "[`scripts/build_v5_g2_cost_time_table.py`](../../../../scripts/build_v5_g2_cost_time_table.py) "
        "from [`../results.json`](../results.json)."
    )
    L.append("")
    L.append(
        f"**{len(ledger)}/{len(ledger)} tasks done; {o['n_valid_trials']} valid trials of "
        f"{5*len(ledger)}, all individually audited (0 unresolved infra problems; 4 tasks' final "
        f"5 were pooled across repeated attempts rather than from one run -- see `../summary.md`).** "
        f"Cost: ${o['cost_usd']:,.2f}. Tokens: {o['tokens']:,}. "
        f"Summed task time: {o['seconds']/60:.1f} min ({o['seconds']/3600:.2f} hr) -- "
        f"summed across tasks; the sweep ran at 10- to 15-way concurrency on CCC/LSF, so elapsed "
        f"wall-clock was far less (see `recipes/v5/v5_g2_e1/README.md`)."
    )
    L.append("")
    L.append(
        f"`v5_b1` is `v5_b1_e1`'s own reward on the same task (the original, unmodified skill); "
        f"`Δ vs b1` = this arm minus that. "
        f"**{o['n_variable']} of {len(ledger)} tasks ({o['pct_variable']:.1f}%) are "
        f"non-deterministic**; see `../summary.md`."
    )
    L.append("")
    L.append("## Summary table")
    L.append("")
    L.append("| # | Task | set | origin | Reward(val) | stderr | Trial rewards | sd "
             "| v5_b1 | Δ vs b1 | move | Cost($) | Tokens | Time(s) |")
    L.append("|---|---|:--|:--|---|---|---|---|---|---|:--|---|---|---|")
    for i, r in enumerate(ledger, 1):
        trials = ", ".join(f"{v:.3f}" for v in (r["trial_rewards"] or []))
        L.append(
            f"| {i} | {r['task']} | {r['task_set']} | {r['origin']} | {r['reward']:.4f} | {r['stderr']:.4f} "
            f"| {trials} | {r['sd']:.3f} | {r['v5_b1_reward']:.4f} | {r['delta_vs_v5_b1']:+.4f} "
            f"| {r['move']} | {r['cost_usd']:.4f} | {r['tokens']:,} | {r['seconds']:.1f} |"
        )
    L.append("")
    return "\n".join(L)


def main():
    check_only = "--check" in sys.argv
    results = json.loads(RESULTS_JSON.read_text())
    new_text = render(results)
    old_text = TABLE_MD.read_text() if TABLE_MD.exists() else None

    if old_text == new_text:
        print("v5_g2_e1_results_table.md already up to date.")
        return 0
    if check_only:
        print("v5_g2_e1_results_table.md is STALE relative to results.json.", file=sys.stderr)
        return 1

    TABLE_MD.parent.mkdir(parents=True, exist_ok=True)
    TABLE_MD.write_text(new_text)
    print(f"Wrote {TABLE_MD.relative_to(ROOT)} ({len(results['task_ledger'])} tasks).")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
