#!/usr/bin/env python3
"""Scaffold one cap-evolve project per task for an h4 EVALUATION sweep.

An h4 sweep answers "what does artifact X score on these tasks", with no
optimizer in the loop: each project is evaluated at ``--max-iterations 0``, so
cap-evolve measures the project's seed and stops. The artifact under test is
therefore installed as each project's ``seed_capability/``.

Layout (one project per task, each with its OWN parent directory):

    .capevolve/
      h4_common/
        adapters  -> ../../scripts/parsec/v4_t2_e1/common/adapters   (symlink)
        optimizer -> ../../scripts/parsec/v4_t2_e1/common/optimizer  (symlink)
      h4_<suite>_<task-id>/
        project/
          seed_capability/*.md   (the 8 files of the artifact under test)
          capevolve.yaml
          split_ids.json
          adapters  -> ../../h4_common/adapters   (symlink)
          optimizer -> ../../h4_common/optimizer  (symlink)

The extra directory level is not cosmetic. ``cap-evolve run --project <P>``
creates its ``run_<timestamp>/`` under <P>'s PARENT, so giving every task the
same parent would land all of their run dirs in one directory and let
``RunDir.latest()`` resolve to another task's run. Each task gets a unique
parent instead.

The adapter and optimizer are reused from v4_t2_e1 rather than copied: the same
adapter does the right thing here (it reads $TASK_ID, injects the MCP URLs, and
recovers cost from parsec-live's own usage log), and a second copy would be one
more thing to keep in step.

Usage:
    export PARSEC_V4N=/path/to/rhdp-parsec/v4_2026-09-16
    python3 scripts/parsec/h4/scaffold_eval_projects.py \
        --suite-id base01 --artifact <dir-of-8-md-files>
    # ... --tasks all      every bench-v4-* task in the tree (default, 34)
    # ... --tasks targets  only the 21 that scored sub-1.0 at baseline
    # ... --tasks a,b,c    an explicit list
"""
from __future__ import annotations

import argparse
import os
import shutil
import sys
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parents[3]
CAPEVOLVE_DIR = REPO_ROOT / ".capevolve"
V4T2_DIR = REPO_ROOT / "scripts" / "parsec" / "v4_t2_e1"
COMMON_ADAPTERS_SRC = V4T2_DIR / "common" / "adapters"
COMMON_OPTIMIZER_SRC = V4T2_DIR / "common" / "optimizer"

# parsec_paths is the one source of truth for $PARSEC_V4N resolution and its
# error wording; v4_t2_e1's scaffolder is the one source of truth for the
# 21-task target set. Import both rather than restating either.
sys.path.insert(0, str(V4T2_DIR / "common"))
sys.path.insert(0, str(V4T2_DIR))
import parsec_paths  # noqa: E402

TASK_DIR_PREFIX = "bench-v4-"

PROMPT_FILES = [
    "orchestrator.md",
    "shared_context.md",
    "aap2_agent.md",
    "babylon_agent.md",
    "cost_agent.md",
    "icinga_agent.md",
    "ocpv_agent.md",
    "security_agent.md",
]


def target_task_ids() -> list[str]:
    """The 21 sub-1.0 tasks, read from v4_t2_e1's scaffolder."""
    import scaffold_projects

    return list(scaffold_projects.TASK_IDS)


def all_task_ids(v4n: Path) -> list[str]:
    """Every task the benchmark tree actually carries (34 at v4_2026-09-16)."""
    tasks_dir = v4n / "_run" / "tasks"
    if not tasks_dir.is_dir():
        raise RuntimeError(f"task dir not found: {tasks_dir}")
    return sorted(
        d.name[len(TASK_DIR_PREFIX):]
        for d in tasks_dir.glob(f"{TASK_DIR_PREFIX}*")
        if d.is_dir()
    )


def render_capevolve_yaml(num_trials: int, max_usd: float) -> str:
    # Mirrors v4_t2_e1's project yaml so a reader can diff the two, with
    # max_iterations pinned to 0: this project is measured, never optimized.
    # The optimizer_* keys stay because the schema carries them and a reader
    # should see they are inert here, not absent by accident.
    return f"""\
# h4 evaluation project — measured at --max-iterations 0, never optimized.
# Generated by scripts/parsec/h4/scaffold_eval_projects.py; edits are overwritten.
optimizer_skill: claude-code
optimizer_model: claude-opus-5
algorithm_skill: hill-climb
target_model: claude-sonnet-4-6
capabilities: [system-prompt]
split_ids_file: split_ids.json
num_trials: {num_trials}
max_iterations: 0
max_usd: {max_usd}
"""


def render_split_ids(task_id: str) -> str:
    # train == val == test == the one task. cap-evolve's baseline() measures
    # val, which is what an h4 sweep reads back; train and test are pinned to
    # the same id so nothing downstream can draw a random split.
    return (
        "{\n"
        f'  "train": ["{task_id}"],\n'
        f'  "val":   ["{task_id}"],\n'
        f'  "test":  ["{task_id}"]\n'
        "}\n"
    )


def _ensure_symlink(link: Path, target: Path) -> Path:
    """Create ``link`` -> relative(``target``) if missing; verify it if present."""
    link.parent.mkdir(parents=True, exist_ok=True)
    rel_target = Path(os.path.relpath(target, start=link.parent))
    if link.is_symlink() or link.exists():
        if link.resolve() != target.resolve():
            raise RuntimeError(
                f"{link} already exists and does not point at {target} "
                f"(points at {link.resolve()})"
            )
        return link
    link.symlink_to(rel_target, target_is_directory=True)
    return link


def validate_artifact(artifact: Path) -> None:
    if not artifact.is_dir():
        raise RuntimeError(f"artifact is not a directory: {artifact}")
    missing = [n for n in PROMPT_FILES if not (artifact / n).is_file()]
    if missing:
        raise RuntimeError(
            f"artifact {artifact} is missing {len(missing)} of the 8 prompt "
            f"files: {missing}. An incomplete bundle would be evaluated as a "
            f"mix of this artifact and whatever the lane already served."
        )
    # A prompt file that is present but empty scores as a silently degraded
    # bundle rather than an error, so refuse it here instead.
    empty = [n for n in PROMPT_FILES if (artifact / n).stat().st_size < 32]
    if empty:
        raise RuntimeError(f"artifact {artifact} has suspiciously small prompts: {empty}")


def scaffold_all(
    suite_id: str,
    artifact: Path,
    task_ids: list[str],
    *,
    capevolve_dir: Path = CAPEVOLVE_DIR,
    num_trials: int = 5,
    max_usd: float = 50.0,
    common_adapters_src: Path = COMMON_ADAPTERS_SRC,
    common_optimizer_src: Path = COMMON_OPTIMIZER_SRC,
    force: bool = False,
) -> list[Path]:
    created: list[Path] = []

    common_dir = capevolve_dir / "h4_common"
    created.append(_ensure_symlink(common_dir / "adapters", common_adapters_src))
    created.append(_ensure_symlink(common_dir / "optimizer", common_optimizer_src))

    for task_id in task_ids:
        proj = capevolve_dir / f"h4_{suite_id}_{task_id}" / "project"
        seed_dir = proj / "seed_capability"
        seed_dir.mkdir(parents=True, exist_ok=True)

        # Unlike v4_t2_e1's scaffolder, the seed here is always refreshed from
        # the artifact: the artifact IS the thing under test, so a stale seed
        # left from a previous suite would quietly measure the wrong bundle.
        # force only gates the surrounding project files.
        for name in PROMPT_FILES:
            dst = seed_dir / name
            shutil.copyfile(artifact / name, dst)
            created.append(dst)

        yaml_path = proj / "capevolve.yaml"
        if force or not yaml_path.exists():
            yaml_path.write_text(render_capevolve_yaml(num_trials, max_usd), encoding="utf-8")
        created.append(yaml_path)

        split_path = proj / "split_ids.json"
        if force or not split_path.exists():
            split_path.write_text(render_split_ids(task_id), encoding="utf-8")
        created.append(split_path)

        created.append(_ensure_symlink(proj / "adapters", common_dir / "adapters"))
        created.append(_ensure_symlink(proj / "optimizer", common_dir / "optimizer"))

    return created


def resolve_task_ids(spec: str, v4n: Path) -> list[str]:
    if spec == "all":
        return all_task_ids(v4n)
    if spec == "targets":
        return target_task_ids()
    ids = [t.strip() for t in spec.split(",") if t.strip()]
    known = set(all_task_ids(v4n))
    unknown = [t for t in ids if t not in known]
    if unknown:
        raise RuntimeError(f"unknown task id(s): {unknown}")
    return ids


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__,
                                     formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--suite-id", required=True,
                        help="names this sweep; becomes part of each project dir")
    parser.add_argument("--artifact", required=True,
                        help="directory holding the 8 prompt .md files to evaluate")
    parser.add_argument("--tasks", default="all",
                        help="'all' (default), 'targets' (the 21 sub-1.0), or a comma list")
    parser.add_argument("--num-trials", type=int, default=5)
    parser.add_argument("--max-usd", type=float, default=50.0)
    parser.add_argument("--force", action="store_true",
                        help="also rewrite capevolve.yaml/split_ids.json if present")
    parser.add_argument("--dry-run", action="store_true")
    args = parser.parse_args()

    if not args.suite_id.replace("-", "").replace("_", "").isalnum():
        print("--suite-id must be alphanumeric with - or _", file=sys.stderr)
        return 1

    v4n = parsec_paths.resolve_v4n_or_none()
    if v4n is None:
        print(parsec_paths.V4N_REQUIRED_MSG, file=sys.stderr)
        return 1

    try:
        task_ids = resolve_task_ids(args.tasks, v4n)
        artifact = Path(args.artifact).resolve()
        validate_artifact(artifact)
    except RuntimeError as e:
        print(f"ERROR: {e}", file=sys.stderr)
        return 1

    if args.dry_run:
        print(f"suite {args.suite_id}: {len(task_ids)} task(s), artifact {artifact}")
        for t in task_ids:
            print(f"  would scaffold {CAPEVOLVE_DIR / f'h4_{args.suite_id}_{t}' / 'project'}")
        return 0

    for label, src in (("common adapters source", COMMON_ADAPTERS_SRC),
                       ("common optimizer source", COMMON_OPTIMIZER_SRC)):
        if not src.exists():
            print(f"{label} not found: {src} — scaffolding now would create "
                  f"dangling symlinks in every project. Nothing was written.",
                  file=sys.stderr)
            return 1

    paths = scaffold_all(
        args.suite_id, artifact, task_ids,
        num_trials=args.num_trials, max_usd=args.max_usd, force=args.force,
    )
    print(f"suite {args.suite_id}: scaffolded {len(task_ids)} project(s), "
          f"{len(paths)} paths touched, artifact {artifact}")
    # The sweep driver reads this file to know what to fan out over.
    manifest = CAPEVOLVE_DIR / f"h4_{args.suite_id}.tasks"
    manifest.write_text("\n".join(task_ids) + "\n", encoding="utf-8")
    print(f"task manifest: {manifest}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
