#!/usr/bin/env python3
"""Build results/v5/v5_t1_e1/cost_time/v5_t1_e1_results_table.md from
results/v5/v5_t1_e1/results.json.

Mirrors v4_t4_e1_results_table.md's shape (one zero-shot baseline eval per
task, no optimization step), but reads the already-built results.json rather
than a markdown table vendored from the intake worktree -- v5 has no such
upstream script, so results.json is the single source of truth here and this
table is purely a human-readable rendering of it, not an input to anything.

Usage: python3 scripts/build_v5_t1_cost_time_table.py [--check]
  --check   exit 1 if regenerating would change the table, instead of writing it.
"""
import sys
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
RESULTS_JSON = ROOT / "results" / "v5" / "v5_t1_e1" / "results.json"
TABLE_MD = ROOT / "results" / "v5" / "v5_t1_e1" / "cost_time" / "v5_t1_e1_results_table.md"


def render(results):
    ledger = results["task_ledger"]
    total_cost = sum(r["cost_usd"] for r in ledger if r["cost_usd"] is not None)
    total_tokens = sum(r["tokens"] for r in ledger if r["tokens"] is not None)
    total_s = sum(r["seconds"] for r in ledger if r["seconds"] is not None)

    lines = []
    lines.append("# v5_t1_e1 -- T1 (original skill) zero-shot sweep: cost & time")
    lines.append("")
    lines.append(
        "One row per task -- each task is exactly ONE baseline eval (5 trials), "
        "zero-shot, no optimization step. Generated by "
        "[`scripts/build_v5_t1_cost_time_table.py`](../../../../scripts/build_v5_t1_cost_time_table.py) "
        "from [`../results.json`](../results.json)."
    )
    lines.append("")
    lines.append(
        f"**{len(ledger)}/{len(ledger)} tasks done.** Cost: ${total_cost:,.2f}. "
        f"Tokens: {total_tokens:,}. Wall time: {total_s/60:.1f} min "
        f"({total_s/3600:.2f} hr) -- summed across all tasks; the sweep itself "
        f"ran at 5-13x concurrency on CCC/LSF, so elapsed wall-clock was far "
        f"less than this sum (see `recipes/v5/v5_t1_e1/README.md`)."
    )
    lines.append("")
    lines.append("## Summary table")
    lines.append("")
    lines.append(
        "| # | Task | Reward(val) | stderr | Trial rewards | Errored | Headroom "
        "| Cost($) | Tokens | Time(s) |"
    )
    lines.append("|---|---|---|---|---|---|---|---|---|---|")
    for i, r in enumerate(ledger, 1):
        trials = ", ".join(f"{v:.3f}" for v in (r["trial_rewards"] or []))
        lines.append(
            f"| {i} | {r['task']} | {r['reward']:.4f} | {r['stderr']:.4f} | {trials} "
            f"| {r['errored_trials']} | {r['headroom']} | {r['cost_usd']:.4f} "
            f"| {r['tokens']:,} | {r['seconds']:.1f} |"
        )
    lines.append("")
    return "\n".join(lines)


def main():
    check_only = "--check" in sys.argv
    results = json.loads(RESULTS_JSON.read_text())
    new_text = render(results)
    old_text = TABLE_MD.read_text() if TABLE_MD.exists() else None

    if old_text == new_text:
        print("v5_t1_e1_results_table.md already up to date.")
        return 0
    if check_only:
        print("v5_t1_e1_results_table.md is STALE relative to results.json.", file=sys.stderr)
        return 1

    TABLE_MD.parent.mkdir(parents=True, exist_ok=True)
    TABLE_MD.write_text(new_text)
    print(f"Wrote {TABLE_MD.relative_to(ROOT)} ({len(results['task_ledger'])} tasks).")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
