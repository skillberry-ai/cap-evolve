#!/usr/bin/env python3
"""Writes appendix/config_generated.tex from analysis/out/metrics/configs_by_arm.json.

One row per (suite, arm), taken from seed 0; the script checks that seeds 1 and 2
carry the same settings apart from paths and seed, and says so in the table note
otherwise. Run with python3 -I.
"""
import json
import pathlib
import re

ROOT = pathlib.Path(__file__).resolve().parent.parent.parent
runs = json.load(open(ROOT / "analysis/out/metrics/configs_by_arm.json"))["runs"]
OUT = ROOT / "paper" / "appendix" / "config_generated.tex"

DROP = {"out", "run-dir", "tag-prefix", "seed", "project", "from-dir", "note", "optimizer_instructions_file",
        "capability_path", "dataset_source", "split_ids_file", "store", "-", "verbose", "output-format",
        "permission-mode", "allowedTools", "disallowedTools", "capability_sources", "base_", "_base_", "split_seed", "created_at"}
DROP_PREFIX = ("azure_openai", "claude_code_exec", "codex_exec")
NAMES = {"ace": "ACE", "ao": "CapEvolve agent-optimize", "hc": "CapEvolve hill-climb", "evoskill": "EvoSkill",
         "gepa": "GEPA", "metaharness": "Meta-Harness", "mipro": "MIPROv2", "skillopt": "SkillOpt",
         "trace2skill": "Trace2Skill", "wikiskill": "WikiSkill (community)", "ctl-oneshot": "One-shot repair",
         "ctl-seed": "Unoptimized seed", "graphskillevo": "GraphSkillEvo", "mce": "MCE", "memento": "Memento-Skills",
         "harnesslens": "HarnessLens"}
ORDER = ["hc", "ao", "gepa", "skillopt", "metaharness", "evoskill", "wikiskill", "trace2skill", "ace", "mipro",
         "harnesslens", "ctl-seed", "ctl-oneshot", "graphskillevo", "mce", "memento"]


def esc(s):
    s = str(s)
    for a, b in (("\\", "/"), ("&", "\\&"), ("%", "\\%"), ("_", "\\_\\allowbreak{}"), ("#", "\\#"), ("$", "\\$"),
                 ("{", "\\{"), ("}", "\\}"), ("~", "\\~{}"), ("^", "\\^{}")):
        s = s.replace(a, b)
    return s


def flat(hp):
    out = {}
    if not isinstance(hp, dict):
        return out
    for fname, blob in hp.items():
        if not isinstance(blob, dict):
            continue
        for k, v in blob.items():
            if k in DROP or k.startswith(DROP_PREFIX) or isinstance(v, (dict, list)) and k not in ("capabilities",):
                continue
            if isinstance(v, list):
                v = ",".join(map(str, v))
            v = str(v).replace('rits/', '').replace('ibm-ete-int/', '').replace('ibm-ete/', '').replace('ibm-rits/', '')
            if v.startswith("/") or len(v) > 60 or v in ("true`", "|"):
                continue
            out[k] = v
    return out


def sig(r):
    return json.dumps(flat(r["hyperparameters_and_specs"]), sort_keys=True)


lines = []
differs = []
for suite in "ABC":
    arms = sorted({k.split("/")[1] for k in runs if k.startswith(suite + "/")},
                  key=lambda a: ORDER.index(a) if a in ORDER else 99)
    lines.append(f"\\subsection*{{Suite {suite}}}\n\\small\n\\begin{{longtable}}{{@{{}}p{{0.17\\textwidth}}p{{0.11\\textwidth}}p{{0.62\\textwidth}}@{{}}}}")
    lines.append("\\toprule\nArm & Status & Settings read from the run record (seed 0) \\\\\n\\midrule\n\\endhead")
    for a in arms:
        r0 = runs.get(f"{suite}/{a}/s0")
        if not r0:
            continue
        for s in ("s1", "s2"):
            rs = runs.get(f"{suite}/{a}/{s}")
            if rs and sig(rs) != sig(r0):
                differs.append(f"{suite}/{a}/{s}")
        kv = flat(r0["hyperparameters_and_specs"])
        txt = "; ".join(f"{esc(k)}={esc(v)}" for k, v in sorted(kv.items())) or "not recorded"
        sha = r0["method_version_or_sha"]
        if isinstance(sha, dict):
            shas = sha.get("shas_from_manifests")
            if isinstance(shas, dict):
                k0 = sorted(shas)[0]
                txt += f"; pin {esc(k0)}={esc(str(shas[k0])[:12])}"
        lines.append(f"{esc(NAMES.get(a, a))} & {esc(r0['status'].replace('_', ' '))} & {txt} \\\\")
    lines.append("\\bottomrule\n\\end{longtable}")
note = ("Seeds 1 and 2 carry the same recorded settings as seed 0 except paths and seed."
        if not differs else "Settings differ between seeds for: " + ", ".join(differs) + ".")
lines.append(f"\\noindent {note} Values read as ``not recorded'' in the run record are shown as absent, not guessed.")
OUT.write_text("% GENERATED by scripts/gen_config_tables.py. Do not edit by hand.\n" + "\n".join(lines) + "\n")
print("wrote", OUT, "differs:", differs)
