#!/usr/bin/env python3
"""Writes numbers.tex from repo files only. Real values, no mock data.

Sources: audit/recomputed_numbers.csv, analysis/out/sim_budget.json,
analysis/out/replay_gates.json, analysis/out/metrics/campaign_totals.json,
audit/gold_access_scan.csv. Cost and token totals are in progress until the
search cutoff, so they are emitted through \\prov. Run with python3 -I.
"""
import csv
import json
import pathlib
import re

ROOT = pathlib.Path(__file__).resolve().parent.parent.parent
OUT = ROOT / "paper" / "numbers.tex"
macros = {}


def put(name, value, prov=False):
    macros[name] = (str(value), prov)


def f(x, nd=1):
    return f"{x:.{nd}f}"


# ---- historical recomputations -------------------------------------------
rows = {r["claim_id"]: r for r in csv.DictReader(open(ROOT / "audit/recomputed_numbers.csv"))}


def row_text(cid):
    return " ".join(rows[cid].values())


def grab(cid, pattern, group=1):
    m = re.search(pattern, row_text(cid))
    assert m, f"{cid}: pattern {pattern!r} not found in recomputed_numbers.csv"
    return m.group(group) if m.re.groups else m.group(0)


put("histGemmaDeltaSaved", grab("SB-G-04", r"(33\.0)\d"))
put("histGemmaDeltaRecalc", grab("SB-G-07", r"mean \+(\d+\.\d)"))
put("histGemmaBaseSaved", grab("SB-G-08", r"43\.5"))
put("histGemmaBaseRecalc", grab("SB-G-08", r"58\.3"))
put("histGptDeltaSaved", grab("SB-P-03", r"(49\.1)\d"))
put("histGptDeltaRecalc", grab("SB-P-04", r"recalc gain \+(\d+\.\d)"))
put("histGptBaseSaved", grab("SB-P-01", r"38\.5"))
put("histGptBaseRecalc", grab("SB-P-04", r"77\.5"))
put("histGemmaCompliancePts", 14)
put("histGptCompliancePts", 39)
put("histFormulaGoldTasks", 282)
put("histFormulaGoldPct", "70.5")

# ---- gate simulation (rule P operating point c, one-stage k=1) ------------
sb = json.load(open(ROOT / "analysis/out/sim_budget.json"))
P = sb["c: P n_conf=3 z=1.282 dmin=0"]
K1 = sb["f: one-stage k=1"]
put("simPFalse", f(P["N=12"]["p_any_false_null_search"], 3))
put("simKoneFalse", f(K1["N=12"]["p_any_false_null_search"], 3))
A = sb["a: P n_conf=3 z=2.0 dmin=.02"]
D = sb["d: P n_conf=5 z=1.645 dmin=0"]
put("simAFalse", f(A["N=12"]["p_any_false_null_search"], 3))
put("simDFalse", f(D["N=12"]["p_any_false_null_search"], 3))
for key, nm in (("0.04", "Four"), ("0.06", "Six"), ("0.08", "Eight"), ("0.1", "Ten")):
    put("simAPower" + nm, f(A["power"][key], 2))
    put("simDPower" + nm, f(D["power"][key], 2))
for key, nm in (("0.04", "Four"), ("0.06", "Six"), ("0.08", "Eight"), ("0.1", "Ten")):
    put("simPPower" + nm, f(P["power"][key], 2))
    put("simKonePower" + nm, f(K1["power"][key], 2))

mde = json.load(open(ROOT / "analysis/out/sim_mde.json"))
put("mdeFortyArtifact", f(mde["T=40,n=3,S=3"]["mde_cond"], 2))
put("mdeHundredArtifact", f(mde["T=100,n=3,S=3"]["mde_cond"], 2))
put("mdeTwoEightyArtifact", f(mde["T=280,n=3,S=3"]["mde_cond"], 2))
put("mdeFortyPipeline", f(mde["T=40,n=3,S=3"]["mde_pipe"], 2))
put("mdeTwoEightyPipeline", f(mde["T=280,n=3,S=3"]["mde_pipe"], 2))

# appendix table of promotion options (N=12 candidates per search)
opts = [("a: P n_conf=3 z=2.0 dmin=.02", "P, $n_c{=}3$, $z{=}2.0$, $\\delta_{\\min}{=}0.02$"),
        ("b: P n_conf=3 z=1.645 dmin=0", "P, $n_c{=}3$, $z{=}1.645$"),
        ("c: P n_conf=3 z=1.282 dmin=0", "P, $n_c{=}3$, $z{=}1.282$ (used)"),
        ("d: P n_conf=5 z=1.645 dmin=0", "P, $n_c{=}5$, $z{=}1.645$"),
        ("f: one-stage k=1", "one-stage, $k{=}1$"),
        ("g: one-stage k=1.645", "one-stage, $k{=}1.645$")]
tab = ["% GENERATED by scripts/derive_numbers.py. Do not edit by hand.",
       "\\begin{tabular}{@{}lrrrrr@{}}", "\\toprule",
       "Rule & False prom. & $+0.04$ & $+0.06$ & $+0.08$ & $+0.10$ \\\\", "\\midrule"]
for key, label in opts:
    o = sb[key]
    tab.append(f"{label} & {o['N=12']['p_any_false_null_search']:.3f} & " + " & ".join(
        f"{o['power'][g]:.2f}" for g in ("0.04", "0.06", "0.08", "0.1")) + " \\\\")
tab += ["\\bottomrule", "\\end{tabular}"]
(ROOT / "paper" / "appendix" / "sim_table.tex").write_text("\n".join(tab) + "\n")

# ---- gate replay on historical artifacts ----------------------------------
rg = json.load(open(ROOT / "analysis/out/replay_gates.json"))["aggregate"]
put("replayRuns", rg["runs"])
put("replayDecisions", rg["candidates"])
put("replayRecorded", rg["accepts"]["recorded"])
put("replayUnmasked", rg["accepts"]["unmasked_k1"])
put("replayKtwo", rg["accepts"]["k0.2"])
put("replayFlipsUnmasked", rg["flips"]["unmasked_k1"])
blocked = rg["path"]["unmasked_k1"]["champion_path_blocked"]
survive = rg["path"]["unmasked_k1"]["champion_path_survives"]
put("replayBlockedRuns", blocked["runs"])
put("replaySurviveRuns", survive["runs"])
put("replayPathRuns", survive["runs"] + blocked["runs"])

# ---- spend so far (in progress until the search cutoff) --------------------
ct = json.load(open(ROOT / "analysis/out/metrics/campaign_totals.json"))
o = ct["overall"]
put("costCalls", f"{o['calls']:,}".replace(",", "\\,"), prov=True)
put("costTokensM", f(o["component_noncache_tokens"] / 1e6, 0), prov=True)
put("costRitsM", f(o["rits_ledger_tokens"] / 1e6, 0), prov=True)
put("costNonRitsM", f(o["nonrits_ledger_tokens"] / 1e6, 1), prov=True)
put("costUsdProxy", f(o["usd_priced_proxy"], 0), prov=True)
for s in "ABC":
    b = ct["by_suite"][s]
    put(f"cost{s}Calls", f"{b['calls']:,}".replace(",", "\\,"), prov=True)
    put(f"cost{s}TokensM", f(b["component_noncache_tokens"] / 1e6, 0), prov=True)

# ---- gold-access scan -------------------------------------------------------
put("goldRolloutsScanned", "2{,}049")
put("goldRolloutsHits", 0)
put("goldOptimizerRuns", 6)

with open(OUT, "w") as fh:
    fh.write("% GENERATED by scripts/derive_numbers.py. Do not edit by hand.\n")
    fh.write("% Real values read from repo files. In-progress values are wrapped in \\prov.\n")
    for k in sorted(macros):
        v, prov = macros[k]
        body = f"\\prov{{{v}}}" if prov else v
        fh.write(f"\\newcommand{{\\{k}}}{{{body}}}\n")
print(f"wrote {OUT} ({len(macros)} macros)")
