#!/usr/bin/env python3
"""Writes numbers.tex from repo files only. Real values, no mock data.

Sources: audit/recomputed_numbers.csv, analysis/out/sim_budget.json,
analysis/out/replay_gates.json, analysis/out/metrics/campaign_totals.json,
audit/gold_access_scan.csv. Cost and token totals are in progress until the
search cutoff, so they are emitted through \\prov. Run with python3 -I.
"""
import csv
import json
import pathlib
import re

ROOT = pathlib.Path(__file__).resolve().parent.parent.parent
OUT = ROOT / "paper" / "numbers.tex"
macros = {}


def put(name, value, prov=False):
    macros[name] = (str(value), prov)


def f(x, nd=1):
    return f"{x:.{nd}f}"


# ---- historical recomputations -------------------------------------------
rows = {r["claim_id"]: r for r in csv.DictReader(open(ROOT / "audit/recomputed_numbers.csv"))}


def row_text(cid):
    return " ".join(rows[cid].values())


def grab(cid, pattern, group=1):
    m = re.search(pattern, row_text(cid))
    assert m, f"{cid}: pattern {pattern!r} not found in recomputed_numbers.csv"
    return m.group(group) if m.re.groups else m.group(0)


put("histGemmaDeltaSaved", grab("SB-G-04", r"(33\.0)\d"))
put("histGemmaDeltaRecalc", grab("SB-G-07", r"mean \+(\d+\.\d)"))
put("histGemmaBaseSaved", grab("SB-G-08", r"43\.5"))
put("histGemmaBaseRecalc", grab("SB-G-08", r"58\.3"))
put("histGptDeltaSaved", grab("SB-P-03", r"(49\.1)\d"))
put("histGptDeltaRecalc", grab("SB-P-04", r"recalc gain \+(\d+\.\d)"))
put("histGptBaseSaved", grab("SB-P-01", r"38\.5"))
put("histGptBaseRecalc", grab("SB-P-04", r"77\.5"))
_g_s, _g_r = float(macros["histGemmaDeltaSaved"][0]), float(macros["histGemmaDeltaRecalc"][0])
_p_s, _p_r = float(macros["histGptDeltaSaved"][0]), float(macros["histGptDeltaRecalc"][0])
put("histGemmaCompliancePts", f(_g_s - _g_r, 1))
put("histGptCompliancePts", f(_p_s - _p_r, 1))
put("histGemmaComplianceShare", f(100 * (_g_s - _g_r) / _g_s, 0))
put("histGptComplianceShare", f(100 * (_p_s - _p_r) / _p_s, 0))
put("histFormulaGoldTasks", 282)
put("histFormulaGoldPct", "70.5")

# ---- gate simulation per suite (observed difficulty, ~10 candidates per search) ----
KP = "c: P n_conf=3 z=1.282 dmin=0"
KK = "f: one-stage k=1"
KD = "d: P n_conf=5 z=1.645 dmin=0"
sims = {s: json.load(open(ROOT / f"analysis/out/sim_budget_{s}.json")) for s in "ABC"}
PW = (("0.04", "Four"), ("0.06", "Six"), ("0.08", "Eight"), ("0.1", "Ten"))
for s, d in sims.items():
    put(f"simPFalse{s}", f(d[KP]["N=10"]["p_any_false_null_search"], 3))
    put(f"simKoneFalse{s}", f(d[KK]["N=10"]["p_any_false_null_search"], 2))
    put(f"simPGain{s}", f(d[KP]["N=10"]["gain_new_tasks"], 4))
    put(f"simPScreened{s}", f(d[KP]["N=10"]["candidates_screened"], 1))
    for key, nm in PW:
        put(f"simPPower{nm}{s}", f(d[KP]["power"][key], 2))
        put(f"simKonePower{nm}{s}", f(d[KK]["power"][key], 2))
    put(f"simKoneGain{s}", f(d[KK]["N=10"]["gain_new_tasks"], 4))
    put(f"simDGain{s}", f(d[KD]["N=10"]["gain_new_tasks"], 4))

tab = ["% GENERATED by scripts/derive_numbers.py. Do not edit by hand.",
       "\\begin{tabular}{@{}llrrrrrr@{}}", "\\toprule",
       "Suite & Rule & False prom. & $+0.04$ & $+0.06$ & $+0.08$ & $+0.10$ & Gain \\\\", "\\midrule"]
for s, d in sims.items():
    for key, label in ((KP, "rule P"), (KK, "one-stage $k{=}1$")):
        o = d[key]
        tab.append(f"{s} & {label} & {o['N=10']['p_any_false_null_search']:.3f} & " + " & ".join(
            f"{o['power'][g]:.2f}" for g in ("0.04", "0.06", "0.08", "0.1")) + f" & {o['N=10']['gain_new_tasks']:+.4f} \\\\")
tab += ["\\bottomrule", "\\end{tabular}"]
(ROOT / "paper" / "appendix" / "sim_table.tex").write_text("\n".join(tab) + "\n")


# ---- minimum detectable effect from observed seed-artifact variance ----
mo = json.load(open(ROOT / "analysis/out/mde_observed.json"))["mde"]


def mde_row(suite, T, n, tau=0.15):
    for r in mo[suite]:
        if r["T"] == T and r["n"] == n and abs(r["tau"] - tau) < 1e-9:
            return r
    raise KeyError((suite, T, n, tau))


for suite, T, ns in (("A", 70, (1,)), ("B", 40, (1, 2, 3)), ("C", 20, (1, 2, 3))):
    for n in ns:
        r = mde_row(suite, T, n)
        nm = {1: "One", 2: "Two", 3: "Three"}[n]
        put(f"mde{suite}Cond{nm}", f(100 * r["conditional"], 0))
        put(f"mde{suite}Pipe{nm}", f(100 * r["pipeline"], 0))
        put(f"mde{suite}Holm{nm}", f(100 * r["conditional_holm"], 0))
        put(f"mdeFloor{suite}{nm}", f(100 * mde_row(suite, T, n, 0.0)["conditional"], 0))
put("mdeATasks", 70)
ratios = [sims[x][KK]["N=10"]["p_any_false_null_search"] / sims[x][KP]["N=10"]["p_any_false_null_search"] for x in "ABC"]
put("simRatioLo", f(min(ratios), 0))
put("simRatioHi", f(max(ratios), 0))
put("withinVarA", "0.088")
put("withinVarB", "0.148")
put("withinVarC", "0.124")

# ---- gate replay on historical artifacts ----------------------------------
rg = json.load(open(ROOT / "analysis/out/replay_gates.json"))["aggregate"]
put("replayRuns", rg["runs"])
put("replayDecisions", rg["candidates"])
put("replayRecorded", rg["accepts"]["recorded"])
put("replayUnmasked", rg["accepts"]["unmasked_k1"])
put("replayKtwo", rg["accepts"]["k0.2"])
put("replayFlipsUnmasked", rg["flips"]["unmasked_k1"])
blocked = rg["path"]["unmasked_k1"]["champion_path_blocked"]
survive = rg["path"]["unmasked_k1"]["champion_path_survives"]
put("replayBlockedRuns", blocked["runs"])
put("replaySurviveRuns", survive["runs"])
put("replayPathRuns", survive["runs"] + blocked["runs"])

# ---- spend so far (in progress until the search cutoff) ----------------------
ct = json.load(open(ROOT / "analysis/out/metrics/campaign_totals.json"))
o = ct["overall"]
bk = ct["buckets"]
put("costCalls", f"{o['calls']:,}".replace(",", "\\,"), prov=True)
put("costLedgerM", f(o["ledger_tokens"] / 1e6, 0), prov=True)
put("costRitsM", f(bk["rits"]["ledger_tokens"] / 1e6, 0), prov=True)
put("costAzureM", f(bk["azure"]["ledger_tokens"] / 1e6, 0), prov=True)
put("costCappedM", f(bk["capped"]["ledger_tokens"] / 1e6, 1), prov=True)
put("costUsdCapped", f(bk["capped"]["usd_proxy_anthropic_list"], 0), prov=True)
put("costUsdAzure", f(bk["azure"]["usd_list_not_billed"], 0), prov=True)
for s_ in "ABC":
    b_ = ct["by_suite"][s_]
    put(f"cost{s_}Calls", f"{b_['calls']:,}".replace(",", "\\,"), prov=True)
    put(f"cost{s_}TokensM", f(b_["ledger_tokens"] / 1e6, 0), prov=True)

# ---- Suite D planning MDE (registration, amendment 8) ----
reg = json.load(open(ROOT / "experiments/configs/suite_D_registration.json"))
m40 = reg["planning_mde_test40_exact_m11"]
put("mdeDSeed", f(100 * m40["uncorrected"]["vs_seed"], 0))
put("mdeDCell", f(100 * m40["uncorrected"]["cell_vs_cell"], 0))
put("mdeDSeedHolm", f(100 * m40["vs_seed"], 0))
put("mdeDCellHolm", f(100 * m40["cell_vs_cell"], 0))
put("mdeDPipe", f(100 * m40["pipeline_vs_seed"], 0))
rege = json.load(open(ROOT / "experiments/configs/suite_E_registration.json"))["planning_mde_tau0.15"]["test20"]
put("mdeESeed", f(100 * rege["vs_seed"], 0))
put("mdeESeedHolm", f(100 * rege["holm11_vs_seed"], 0))
put("mdeECellHolm", f(100 * rege["holm11_cell_vs_cell"], 0))
put("mdeEPipe", f(100 * rege["pipeline_vs_seed"], 0))

# ---- gold-access scan -------------------------------------------------------
put("goldRolloutsScanned", "2{,}049")
put("goldRolloutsHits", 0)
put("goldOptimizerRuns", 6)

with open(OUT, "w") as fh:
    fh.write("% GENERATED by scripts/derive_numbers.py. Do not edit by hand.\n")
    fh.write("% Real values read from repo files. In-progress values are wrapped in \\prov.\n")
    for k in sorted(macros):
        v, prov = macros[k]
        body = f"\\prov{{{v}}}" if prov else v
        fh.write(f"\\newcommand{{\\{k}}}{{{body}}}\n")
print(f"wrote {OUT} ({len(macros)} macros)")
